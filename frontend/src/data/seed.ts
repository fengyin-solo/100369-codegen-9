function buildSupplySeeds(): EntryRow[] {
  const seeds: EntryRow[] = []
  let id = 0
  for (const farm of FOREST_FARMS) {
    SUPPLY_CATALOG.forEach((item, index) => {
      id += 1
      const stock = REMAIN_STOCK[farm][index]
      const warn = WARN_STOCK[farm][index]
      const status = stock < warn ? '需补充' : stock <= Math.floor(warn * 1.5) ? '偏低' : '充足'
      seeds.push(
        row(id, status, status !== '充足', {
          物资编号: `SUPP-${String(id).padStart(4, '0')}`,
          物资名称: item.name,
          物资类别: item.name.includes('食品') ? '后勤物资' : '扑救物资',
          规格型号: '标准扑救配置',
          储备林场: farm,
          计量单位: item.unit,
          预警储备量: warn,
          实际储备量: stock,
          物资状态: status,
        }),
      )
    })
  }
  return seeds
}

function buildAllocationSeeds(): EntryRow[] {
  const seeds: EntryRow[] = []
  let seq = 0
  for (const hist of ALLOC_HISTORY) {
    SUPPLY_CATALOG.forEach((item, index) => {
      seq += 1
      const qty = ALLOC_PLAN[hist.level][index]
      const status = hist.out ? '已出库' : '待出库'
      seeds.push(
        row(seq, status, !hist.out, {
          调拨单号: `ALLOC-2026-${String(seq).padStart(3, '0')}`,
          关联火情编号: hist.code,
          储备林场: hist.farm,
          物资名称: item.name,
          计量单位: item.unit,
          调拨数量: qty,
          火势等级: hist.level,
          调拨时间: hist.time,
          台账状态: status,
        }),
      )
    })
  }
  return seeds
}

// 各火势等级的调拨基数（顺序对应 SUPPLY_CATALOG）。
