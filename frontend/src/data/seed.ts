import type { EntryRow } from './types'

// 示例数据：首次打开时播种，之后浏览器里的改动优先，重置才会回到这份。

function row(
  id: number,
  status: string,
  pending: boolean,
  fields: Record<string, string | number>,
  abnormal = false,
): EntryRow {
  return { id, status, pending, abnormal, ...fields }
}

